#!/usr/bin/env node

/**
 * Builds `src/gtfs_schedule.ts` from RTD's static GTFS feed.
 *
 * Only rail (route_type 0/1/2) is imported: the live feed is filtered by route
 * and stop anyway, and pulling in the ~7.5k bus stops would balloon the bundle
 * for no benefit.
 *
 * Output shape: for every (route, stop) pair, the scheduled arrival times
 * grouped by service (e.g. weekday / saturday / sunday), stored as minutes
 * since midnight. Run with `npm run import-gtfs`.
 */

import { config } from "./config.js";
import {
  closeDb,
  getCalendars,
  getRoutes,
  getStops,
  getStoptimes,
  getTrips,
  importGtfs,
  openDb,
} from "gtfs";
import fs from "fs";

const RAIL_ROUTE_TYPES = [0, 1, 2];

const db = openDb(config);
await importGtfs({ ...config, db: db });

const railRoutes = getRoutes(
  { route_type: RAIL_ROUTE_TYPES },
  ["route_id", "route_short_name", "route_long_name", "route_type"]
);
const railRouteIds = new Set(railRoutes.map((r) => r.route_id));

// trip_id -> { route_id, service_id }, restricted to rail.
const trips = getTrips(
  { route_id: [...railRouteIds] },
  ["trip_id", "route_id", "service_id"]
);
const tripRoute = new Map(trips.map((t) => [t.trip_id, t]));

// Services that run on at least one day, sorted for a stable output.
const calendars = getCalendars({}, [
  "service_id",
  "sunday",
  "monday",
  "tuesday",
  "wednesday",
  "thursday",
  "friday",
  "saturday",
]);
const services = calendars.map((c) => c.service_id).sort();

// Day-of-week flags, so the worker can pick today's service without shipping
// the full calendar dates range.
const serviceDays = Object.fromEntries(
  calendars.map((c) => [
    c.service_id,
    [
      c.sunday,
      c.monday,
      c.tuesday,
      c.wednesday,
      c.thursday,
      c.friday,
      c.saturday,
    ],
  ])
);

/** "07:38:00" -> 458. Hours can exceed 24 for trips past midnight. */
function toMinutes(time) {
  const [h, m] = time.split(":");
  return Number(h) * 60 + Number(m);
}

const schedules = new Map();
for (const stopTime of getStoptimes({ trip_id: [...tripRoute.keys()] }, [
  "trip_id",
  "stop_id",
  "arrival_time",
])) {
  const trip = tripRoute.get(stopTime.trip_id);
  if (!trip || !stopTime.stop_id || !stopTime.arrival_time) continue;

  const key = `${trip.route_id}|${stopTime.stop_id}`;
  const byService = schedules.get(key) ?? new Map();
  const times = byService.get(trip.service_id) ?? [];
  times.push(toMinutes(stopTime.arrival_time));
  byService.set(trip.service_id, times);
  schedules.set(key, byService);
}

const stopIds = new Set(
  [...schedules.keys()].map((key) => key.split("|")[1])
);
const routeNames = new Map(
  railRoutes.map((r) => [r.route_id, r.route_short_name || r.route_long_name])
);
const stopNames = new Map(
  getStops({ stop_id: [...stopIds] }, ["stop_id", "stop_name"]).map((s) => [
    s.stop_id,
    s.stop_name,
  ])
);

// Per-service minute lists compress well; keep them sorted and de-duplicated.
const output = {};
for (const [key, byService] of [...schedules.entries()].sort()) {
  output[key] = Object.fromEntries(
    [...byService.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([service, times]) => [
        service,
        [...new Set(times)].sort((a, b) => a - b),
      ])
  );
}

const data = {
  services,
  serviceDays,
  routes: Object.fromEntries(
    [...railRouteIds].sort().map((id) => [id, routeNames.get(id)])
  ),
  stops: Object.fromEntries(
    [...stopIds].sort().map((id) => [id, stopNames.get(id) ?? id])
  ),
  schedules: output,
};

fs.writeFileSync(
  "src/gtfs_schedule.ts",
  `// Generated by src/import_gtfs_data.js -- do not edit by hand.
// ${new Date().toISOString()} from ${config.agencies[0].url}

export interface GtfsSchedule {
  /** Service ids, e.g. weekday / saturday / sunday. */
  services: string[];
  /** service_id -> [sun, mon, tue, wed, thu, fri, sat] flags. */
  serviceDays: Record<string, number[]>;
  /** route_id -> display name. */
  routes: Record<string, string>;
  /** stop_id -> display name. */
  stops: Record<string, string>;
  /** "route_id|stop_id" -> service_id -> arrival minutes since midnight. */
  schedules: Record<string, Record<string, number[]>>;
}

export const DATA: GtfsSchedule = ` +
    JSON.stringify(data) +
    ";\n"
);

const pairs = Object.keys(output).length;
console.log(
  `Wrote src/gtfs_schedule.ts: ${railRouteIds.size} routes, ` +
    `${stopIds.size} stops, ${pairs} (route, stop) pairs, ` +
    `${services.length} services`
);

closeDb(db);
